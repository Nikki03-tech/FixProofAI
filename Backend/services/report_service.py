from Backend.schemas import AnalysisResponse


def generate_markdown_report(
    result: AnalysisResponse,
    language: str,
    explanation_level: str,
) -> str:
    """Convert a validated analysis into a downloadable Markdown report."""

    lines = [
        "# FixProof AI — Code Analysis Report",
        "",
        f"- **Language:** {language.title()}",
        f"- **Explanation level:** {explanation_level.title()}",
        "- **Execution status:** Code was not executed",
        "",
        "## Summary",
        "",
        result.summary,
        "",
        "## Issues identified",
        "",
    ]

    if result.issues:
        lines.extend(f"- {issue}" for issue in result.issues)
    else:
        lines.append("No specific issues were identified by the AI analysis.")

    lines.extend(["", "## Root cause", "", result.root_cause, ""])

    lines.extend(["## Suggested fixes", ""])

    if result.suggested_fixes:
        for index, fix in enumerate(result.suggested_fixes, start=1):
            lines.extend(
                [
                    f"### {index}. {fix.title}",
                    "",
                    fix.explanation,
                    "",
                    "```",
                    fix.code,
                    "```",
                    "",
                ]
            )
    else:
        lines.append("No specific fixes were suggested.")

    lines.extend(["", "## Suggested tests", ""])

    if result.tests:
        for index, test in enumerate(result.tests, start=1):
            lines.extend(
                [
                    f"### Test {index}",
                    "",
                    test.description,
                    "",
                    "```",
                    test.test_code,
                    "```",
                    "",
                ]
            )
    else:
        lines.append("No test suggestions were provided.")

    lines.extend(["", "## Limitations", ""])

    if result.limitations:
        lines.extend(f"- {item}" for item in result.limitations)
    else:
        lines.append("AI-generated findings have not been independently verified.")

    lines.extend(
        [
            "",
            "---",
            "Generated by FixProof AI. Review all suggested changes before use.",
            "",
        ]
    )

    return "\n".join(lines)
